def canonical_sector_l2(sector: str, raw: str | None) -> str | None:
    """二级必须属于给定一级。正文没写、对不上，都留空。官方名称带「Ⅱ」时，允许省略这个后缀。"""
    name = " ".join((raw or "").split())
    if not name:
        return None
    if SW_LEVEL2.get(name) == sector:
        return name
    official = name if name.endswith("Ⅱ") else f"{name}Ⅱ"
    if SW_LEVEL2.get(official) == sector:
        return official
    return None


def level2_by_parent() -> str:
    grouped = {parent: [] for parent in SW_INDUSTRIES}
    for name, parent in SW_LEVEL2.items():
        grouped[parent].append(name)
    return "\n".join(f"{parent}：{'、'.join(names)}" for parent, names in grouped.items())


